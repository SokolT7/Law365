import assert from "node:assert/strict";
import { mkdtempSync, readFileSync, writeFileSync, copyFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { pathToFileURL } from "node:url";
import { randomBytes, randomUUID } from "node:crypto";
import { DatabaseSync } from "node:sqlite";
import ts from "typescript";

// Exercise the actual storage/auth implementation against an isolated temporary database.
const directory = mkdtempSync(path.join(tmpdir(), "ltb-platform-test-"));
process.env.LTB_DATABASE_PATH = path.join(directory, "test.sqlite");
delete process.env.VERCEL;
delete process.env.AWS_LAMBDA_FUNCTION_NAME;
const lib = path.join(process.cwd(), "src/lib");
for (const name of ["features", "platform"]) {
  const source = readFileSync(path.join(lib, `${name}.ts`), "utf8");
  const { outputText } = ts.transpileModule(source, { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ES2022 } });
  writeFileSync(path.join(directory, `${name}.mjs`), outputText.replaceAll('"./features"', '"./features.mjs"'));
}
copyFileSync(path.join(lib, "platform-core.mjs"), path.join(directory, "platform-core.mjs"));
const p = await import(pathToFileURL(path.join(directory, "platform.mjs")));
const f = await import(pathToFileURL(path.join(directory, "features.mjs")));
const { hashPassword } = await import(pathToFileURL(path.join(directory, "platform-core.mjs")));
let assertions = 0;
function check(value, message) { assert.ok(value, message); assertions += 1; }
function throws(work, status) { assert.throws(work, (error) => error.status === status); assertions += 1; }
async function rejects(work, status) { await assert.rejects(work, (error) => error.status === status); assertions += 1; }
let fixture;
try {
  check(!p.hasPlatformAdmin(), "Fresh installation has no administrator or demo data");
  check(p.listFirms().length === 0 && p.listUsers().length === 0, "Fresh install is empty");
  fixture = new DatabaseSync(process.env.LTB_DATABASE_PATH);
  const adminId = randomUUID(); const password = randomBytes(24).toString("base64url");
  fixture.prepare("INSERT INTO users VALUES (?,NULL,?,'operator@example.test','platform_admin','active',?,?)").run(adminId, "Test operator", await hashPassword(password), new Date().toISOString());
  check(p.hasPlatformAdmin(), "Explicit administrator bootstrap is detected");
  check(await p.authenticate("operator@example.test", password), "Valid administrator can sign in");
  check(await p.authenticate("missing@example.test", password) === null, "Unknown user cannot sign in");
  check(await p.authenticate("operator@example.test", "incorrect-password") === null, "Wrong password denied");
  throws(() => p.createFirm({ name: "Denied" }, "unknown"), 403);
  throws(() => p.createFirm({ name: "Missing dependency", features: ["document_chat"] }, adminId), 400);
  throws(() => p.createFirm({ name: "Unknown feature", features: ["unknown"] }, adminId), 400);
  const firm = p.createFirm({ name: "Prvi ured", status: "active", features: ["documents", "document_chat", "summary_analysis"] }, adminId);
  const otherFirm = p.createFirm({ name: "Drugi ured", status: "active", features: ["clients"] }, adminId);
  const draft = p.createFirm({ name: "Nacrt ureda" }, adminId);
  check(draft.status === "draft" && draft.features.length === 0, "Firm access defaults closed");
  check(!f.hasFeature(otherFirm, "document_chat") && !f.hasFeature(firm, "unknown"), "Unknown and unavailable features denied");
  const invited = p.inviteUser({ firmId: firm.id, name: "Test member", email: "member@example.test" }, adminId);
  check(p.getInvitationStatus(invited.token)?.firmName === firm.name, "Valid token resolves firm context");
  check(await p.authenticate("member@example.test", password) === null, "Invited user cannot sign in before acceptance");
  throws(() => p.inviteUser({ firmId: otherFirm.id, name: "Duplicate", email: "MEMBER@example.test" }, adminId), 409);
  throws(() => p.inviteUser({ firmId: firm.id, name: "Privilege", email: "privilege@example.test", role: "platform_admin" }, adminId), 400);
  const accepted = await p.acceptInvitation(invited.token, password);
  check(accepted.status === "active" && accepted.firmId === firm.id, "Acceptance activates exactly one firm membership");
  await rejects(() => p.acceptInvitation(invited.token, password), 400);
  check(p.getInvitationStatus(invited.token) === null, "Used invitation cannot be reused");
  const token = p.createSession(accepted.id);
  check(p.resolveSession(token)?.firm.id === firm.id, "Opaque session resolves correct firm");
  check(p.resolveSession(randomBytes(32).toString("base64url")) === null, "Unknown session denied");
  throws(() => p.updateFirm(otherFirm.id, { name: "Denied" }, accepted.id), 403);
  p.updateFirm(firm.id, { features: ["documents", "summary_analysis"] }, adminId);
  check(!f.hasFeature(p.resolveSession(token).firm, "document_chat"), "Feature removal applies to existing sessions immediately");
  const empty = { firm: { id: firm.id, name: firm.name }, user: { id: accepted.id, name: accepted.name, role: "member" }, clients: [], matters: [], documents: [], chunks: [], audit: [] };
  check(p.readFirmData(firm.id) === null && p.readFirmData(otherFirm.id) === null, "No shared legacy data imported");
  check(p.writeFirmData(firm.id, empty, 0) === 1, "Initial tenant data write succeeds");
  throws(() => p.writeFirmData(firm.id, empty, 0), 409);
  check(p.writeFirmData(firm.id, empty, 1) === 2, "Matching revision updates atomically");
  throws(() => p.writeFirmData(firm.id, empty, 1), 409);
  throws(() => p.writeFirmData(otherFirm.id, empty, 0), 403);
  check(p.readFirmData(otherFirm.id) === null, "Other firm data stays isolated");
  const documentId = randomUUID(); empty.documents.push({ id: documentId, title: "Synthetic", filename: "test.txt", type: "", clientId: "", matterId: "", createdAt: new Date().toISOString(), analyses: [] });
  p.writeFirmData(firm.id, empty, 2);
  p.registerJob("job-one", firm.id, documentId, "sazetak");
  check(p.getJob("job-one")?.firmId === firm.id, "Job ownership is persisted");
  throws(() => p.registerJob("job-missing", firm.id, "other-document", "sazetak"), 404);
  throws(() => p.registerJob("job-denied", otherFirm.id, documentId, "sazetak"), 403);
  p.completeJob("job-one"); p.completeJob("job-one", "failed");
  check(p.getJob("job-one")?.status === "complete", "Repeated terminal job updates are idempotent");
  const atomic = structuredClone(empty);
  atomic.documents[0].analyses.push({ jobId: "job-atomic", mode: "sazetak", status: "u_obradi", createdAt: new Date().toISOString() });
  check(p.writeFirmDataAndRegisterJob(firm.id, atomic, 3, "job-atomic", documentId, "sazetak") === 4, "Pending analysis and callback job save atomically");
  check(p.getJob("job-atomic")?.documentId === documentId && p.readFirmData(firm.id).data.documents[0].analyses[0].jobId === "job-atomic", "Atomic write preserves both records");
  atomic.documents[0].analyses.push({ jobId: "job-conflict", mode: "sazetak", status: "u_obradi", createdAt: new Date().toISOString() });
  throws(() => p.writeFirmDataAndRegisterJob(firm.id, atomic, 3, "job-conflict", documentId, "sazetak"), 409);
  check(p.getJob("job-conflict") === null && p.readFirmData(firm.id).revision === 4, "Stale tenant revision leaves no orphan job");
  assert.throws(() => p.writeFirmDataAndRegisterJob(firm.id, atomic, 4, "job-atomic", documentId, "sazetak")); assertions += 1;
  check(p.readFirmData(firm.id).revision === 4 && p.readFirmData(firm.id).data.documents[0].analyses.length === 1, "Job insertion failure rolls back the tenant payload");
  p.updateFirm(firm.id, { status: "suspended" }, adminId);
  throws(() => p.writeFirmDataAndRegisterJob(firm.id, atomic, 4, "job-conflict", documentId, "sazetak"), 403);
  check(p.getJob("job-conflict") === null && p.readFirmData(firm.id).revision === 4, "Suspension is checked inside the transaction before either write");
  check(p.resolveSession(token) === null, "Suspension revokes existing sessions");
  check(await p.authenticate("member@example.test", password) === null, "Suspended firm cannot sign in");
  throws(() => p.createSession(accepted.id), 403);
  p.updateFirm(firm.id, { status: "active" }, adminId);
  check(p.resolveSession(token) === null, "Activation never resurrects old sessions");
  const secondToken = p.createSession(accepted.id);
  p.updateUser(accepted.id, { status: "disabled" }, adminId);
  check(p.resolveSession(secondToken) === null, "Disabling user revokes existing session");
  const renewed = p.updateUser(accepted.id, { action: "invite" }, adminId);
  check(renewed.user.status === "invited" && renewed.token, "Disabled users can be re-invited safely");
  await p.acceptInvitation(renewed.token, password);
  const thirdToken = p.createSession(accepted.id);
  const newPassword = randomBytes(24).toString("base64url");
  await rejects(() => p.changePassword(accepted.id, "wrong-password", newPassword), 400);
  await p.changePassword(accepted.id, password, newPassword);
  check(p.resolveSession(thirdToken) === null, "Password changes revoke all sessions");
  check(await p.authenticate("member@example.test", password) === null, "Old password no longer works");
  check(await p.authenticate("member@example.test", newPassword), "New password works");
  const expiring = p.inviteUser({ firmId: firm.id, name: "Expired", email: "expired@example.test" }, adminId);
  fixture.prepare("UPDATE invitations SET expires_at=0 WHERE user_id=?").run(expiring.user.id);
  await rejects(() => p.acceptInvitation(expiring.token, password), 400);
  const revoked = p.inviteUser({ firmId: firm.id, name: "Revoked", email: "revoked@example.test" }, adminId);
  p.updateUser(revoked.user.id, { action: "revoke_invitation" }, adminId);
  await rejects(() => p.acceptInvitation(revoked.token, password), 400);
  const unaccepted = p.inviteUser({ firmId: firm.id, name: "Unaccepted", email: "unaccepted@example.test" }, adminId);
  p.updateUser(unaccepted.user.id, { status: "disabled" }, adminId);
  const reInvited = p.updateUser(unaccepted.user.id, { action: "invite" }, adminId);
  check(reInvited.user.status === "invited" && reInvited.token, "Disabled unaccepted users can recover invitation");
  for (let index = 0; index < 10; index++) p.checkLoginThrottle("rate-limit@example.test");
  throws(() => p.checkLoginThrottle("rate-limit@example.test"), 429);
  check(p.listPlatformAudit().some((event) => event.action === "Lozinka je promijenjena"), "Security lifecycle changes are audited");
  check(!readFileSync(process.env.LTB_DATABASE_PATH).includes(Buffer.from(password)), "Reusable passwords are never persisted as plaintext");
  console.log(`Platform checks passed: ${assertions} assertions (identity, invitations, sessions, permissions, isolation, concurrency, jobs).`);
} finally { fixture?.close(); rmSync(directory, { recursive: true, force: true }); }
